import fs from 'node:fs';
const shell=fs.readFileSync('public/index.html','utf8');
const css=fs.readFileSync('public/styles.css','utf8');
const js=['bridge.js','app.js','home.js'].map(p=>fs.readFileSync('public/'+p,'utf8'));
// Only public, already-published artwork lives at this pinned URL. Workspace
// data and chat requests still travel exclusively through authenticated tools.
const assetRoot='https://raw.githubusercontent.com/gb69prof/Clara/a6efce459944f72bec530c350c5c74428e824904/public/assets/';
const portrait=assetRoot+'clara.webp';
const homePortrait=assetRoot+'clara-reference.png';
const widget=shell
  .replace(/<link rel="stylesheet"[^>]*>/,()=>'<style>'+css+'</style>')
  .replace(/<script defer[^>]*><\/script>/g,'')
  .replaceAll('assets/clara.webp',()=>portrait)
  .replaceAll('./assets/clara-reference.png',()=>homePortrait)
  .replace('</body>',()=>js.map(s=>'<script>'+s.replaceAll('</script','<\\/script')+'</script>').join('\n')+'</body>');
if(Buffer.byteLength(widget)>200000)throw new Error('Clara widget exceeds its 200 KB loading budget. Keep binary assets out of the HTML resource.');
fs.writeFileSync('lib/clara-ui.ts','// Generated by scripts/generate-ui.mjs\nexport const pageHtml='+JSON.stringify(shell)+';\nexport const widgetHtml='+JSON.stringify(widget)+';\n');
